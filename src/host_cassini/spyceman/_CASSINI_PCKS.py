"""Managed list of the full Cassini PCK files, complete as of 12/15/17.

These are the cpckDDMonYYYY.tpc kernels, the complete Cassini planetary constants product
and the superset of the other two mission PCK lists (ending with _Nav.tpc or _Sci.tpc).
Each one carries masses (BODY*_GM), gravity harmonics (JCOEF, CCOEF, SCOEF), radii, the
full orientation model (POLE_RA, POLE_DEC, PM, LONG_AXIS and the NUT_PREC series), ring
geometry with ring names, atmosphere and magnetic-pole constants, and the AU and RS scale
factors. They cover 35 to 45 bodies, spanning the Sun, the planets Cassini flew past, and
the Saturn and Jupiter satellite systems.

Compared with the other lists in this package:

* _CASSINI_NAV_PCKS holds the navigation subset of the same kernels: gravity only, no
  shapes, no orientation beyond the pole, no rings.
* _CASSINI_SCI_PCKS holds the science subset: everything here except the gravity
  harmonics.
* _CASSINI_ROCK_PCKS and _CASSINI_ROCK_MERGED_PCKS describe a separate product for
  Saturn's small and irregular satellites, bodies 610 and up, which these files barely
  touch.

Where a file's internal date and the date in its name disagree, the release date here is
the later of the two. That applies to 27 of these 199 files.

cpck15Dec2017.tpc is an exception to that rule. It is the PDS-archived copy, and the
PRODUCT_CREATION_TIME of 2017-12-28 in its embedded label is later than the date in its
name; but that records when the archive was built, not when the kernel was issued. Its
own CASSINI_PCK_VERSION agrees with its name, so it is listed under 2017-12-15.
"""

